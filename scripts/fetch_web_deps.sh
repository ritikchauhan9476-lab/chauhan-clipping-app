#!/usr/bin/env bash
# Downloads the parts of the app that are not stored in git: the AI libraries (onnxruntime-web for the Silero
# speech detector, transformers.js for Whisper), the Silero model and the fonts. Run from the repo root.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WEB="$ROOT/web"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

ORT_VER="${ORT_VER:-1.20.1}"
TF_VER="${TF_VER:-3.2.4}"

echo "== npm packages (onnxruntime-web $ORT_VER, transformers.js $TF_VER)"
( cd "$TMP" && npm init -y >/dev/null && npm install --no-audit --no-fund "onnxruntime-web@$ORT_VER" "@huggingface/transformers@$TF_VER" >/dev/null )
mkdir -p "$WEB/vendor/ort" "$WEB/vendor/transformers"
cp "$TMP/node_modules/onnxruntime-web/dist/ort.wasm.min.js" "$WEB/vendor/ort/"
cp "$TMP/node_modules/onnxruntime-web/dist/"ort-wasm-simd-threaded.{wasm,mjs} "$WEB/vendor/ort/"
cp "$TMP/node_modules/@huggingface/transformers/dist/transformers.min.js" "$WEB/vendor/transformers/"
cp "$TMP/node_modules/@huggingface/transformers/dist/"*.wasm "$WEB/vendor/transformers/" 2>/dev/null || true
cp "$TMP/node_modules/@huggingface/transformers/dist/"ort-wasm*.mjs "$WEB/vendor/transformers/" 2>/dev/null || true
ls -la "$WEB/vendor/ort" "$WEB/vendor/transformers"

echo "== Silero VAD model"
curl -fsSL --retry 3 -o "$WEB/vendor/silero_vad.onnx" \
  "https://raw.githubusercontent.com/snakers4/silero-vad/master/src/silero_vad/data/silero_vad.onnx"
ls -la "$WEB/vendor/silero_vad.onnx"

echo "== fonts (Google Fonts, OFL)"
mkdir -p "$WEB/fonts"
G="https://raw.githubusercontent.com/google/fonts/main"
# family|weight|file-in-repo|local-name
FONTS=(
  "Noto Sans|100 900|ofl/notosans/NotoSans%5Bwdth,wght%5D.ttf|NotoSans.ttf"
  "Noto Sans Devanagari|100 900|ofl/notosansdevanagari/NotoSansDevanagari%5Bwdth,wght%5D.ttf|NotoSansDevanagari.ttf"
  "Hind|400|ofl/hind/Hind-Regular.ttf|Hind-Regular.ttf"
  "Hind|700|ofl/hind/Hind-Bold.ttf|Hind-Bold.ttf"
  "Mukta|400|ofl/mukta/Mukta-Regular.ttf|Mukta-Regular.ttf"
  "Mukta|700|ofl/mukta/Mukta-Bold.ttf|Mukta-Bold.ttf"
  "Baloo 2|400 800|ofl/baloo2/Baloo2%5Bwght%5D.ttf|Baloo2.ttf"
  "Rozha One|400|ofl/rozhaone/RozhaOne-Regular.ttf|RozhaOne-Regular.ttf"
  "Teko|300 700|ofl/teko/Teko%5Bwght%5D.ttf|Teko.ttf"
  "Poppins|400|ofl/poppins/Poppins-Regular.ttf|Poppins-Regular.ttf"
  "Poppins|700|ofl/poppins/Poppins-Bold.ttf|Poppins-Bold.ttf"
  "Montserrat|100 900|ofl/montserrat/Montserrat%5Bwght%5D.ttf|Montserrat.ttf"
  "Anton|400|ofl/anton/Anton-Regular.ttf|Anton-Regular.ttf"
  "Bebas Neue|400|ofl/bebasneue/BebasNeue-Regular.ttf|BebasNeue-Regular.ttf"
  "Oswald|200 700|ofl/oswald/Oswald%5Bwght%5D.ttf|Oswald.ttf"
  "Bangers|400|ofl/bangers/Bangers-Regular.ttf|Bangers-Regular.ttf"
  "Lobster|400|ofl/lobster/Lobster-Regular.ttf|Lobster-Regular.ttf"
)
CSS="$WEB/css/fonts.css"
echo "/* generated by scripts/fetch_web_deps.sh */" > "$CSS"
for f in "${FONTS[@]}"; do
  IFS="|" read -r fam wt src name <<< "$f"
  if curl -fsSL --retry 3 -o "$WEB/fonts/$name" "$G/$src"; then
    echo "@font-face { font-family: \"$fam\"; src: url(\"../fonts/$name\") format(\"truetype\"); font-weight: $wt; font-display: swap; }" >> "$CSS"
    echo "  ok  $fam ($wt)"
  else
    echo "  --  $fam ($wt) not found, skipped (the app falls back to Noto Sans)"
    rm -f "$WEB/fonts/$name"
  fi
done
echo "@font-face { font-family: \"Roboto\"; src: local(\"Roboto\"), local(\"Roboto-Regular\"); }" >> "$CSS"
ls -la "$WEB/fonts"
